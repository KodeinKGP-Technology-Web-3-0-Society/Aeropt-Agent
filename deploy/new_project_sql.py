"""Build db/new_project.sql: everything a brand-new Supabase project needs in `public`.

    python deploy/new_project_sql.py                      # rebuild from the committed base
    python deploy/new_project_sql.py --dump ../supabase/migrations/<ts>_remote_schema.sql
                                                          # refresh the base from a new dump first

The base (db/migrations/000_public_base.sql) is the `public` half of a schema dump of
the hosted database. The `django` half is left out on purpose: `manage.py migrate`
creates that schema, and running both would collide. Then every numbered migration
follows in order — they are idempotent, so the ones the dump already reflects are
no-ops — except 008, which is broken (see APPLY.md).
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

MIGRATIONS = Path(__file__).resolve().parents[1] / "db" / "migrations"
BASE = MIGRATIONS / "000_public_base.sql"
OUT = MIGRATIONS.parent / "new_project.sql"
SKIP = {"008_learner_trajectory_view.sql"}
def retired(statement: str) -> bool:
    """agent_memory and sessions.structured_memory were retired by 003; recreating them
    only to drop them again breaks a rerun. The column stays inside CREATE TABLE sessions
    because 003 drops it with IF EXISTS."""
    code = _code(statement)
    if "agent_memory" in code:
        return True
    if "structured_memory" in code:
        return not (code.startswith("CREATE TABLE") or "DROP COLUMN" in code)
    return False


def extract_public(dump: str) -> str:
    statements = [s.strip() for s in re.split(r";\s*\n", dump) if s.strip()]
    keep = [s for s in statements if '"django"' not in s and "django." not in s]
    return (
        "-- 000_public_base.sql — the `public` schema of the hosted database (from a\n"
        "-- `supabase db dump`). Generated by deploy/new_project_sql.py; do not edit by hand.\n\n"
        + ";\n\n".join(keep)
        + ";\n"
    )


def split_statements(sql: str) -> list[str]:
    """Split on `;` at line end, keeping dollar-quoted bodies (functions, DO) whole."""
    out: list[str] = []
    pending = ""
    for piece in re.split(r";[ \t]*\n", sql):
        pending = f"{pending};\n{piece}" if pending else piece
        if len(re.findall(r"\$[A-Za-z_]*\$", pending)) % 2 == 0:
            if pending.strip():
                out.append(pending.strip().rstrip(";"))
            pending = ""
    if pending.strip():
        out.append(pending.strip().rstrip(";"))
    return out


def _code(statement: str) -> str:
    return "\n".join(l for l in statement.splitlines() if not l.lstrip().startswith("--")).strip()


def rerunnable(statement: str) -> str:
    """The dump's DDL fails on a second run; guard it so a half-applied project can rerun."""
    code = _code(statement)
    if re.match(r"CREATE TABLE (?!IF NOT EXISTS)", code):
        return statement.replace("CREATE TABLE ", "CREATE TABLE IF NOT EXISTS ", 1)
    if re.match(r"CREATE (UNIQUE )?INDEX (?!IF NOT EXISTS)", code):
        return re.sub(r"INDEX ", "INDEX IF NOT EXISTS ", statement, count=1)
    if code.startswith("CREATE POLICY") or re.match(r"ALTER TABLE [^;]*\bADD CONSTRAINT\b", code, re.S):
        return (
            f"DO $aeropt$ BEGIN\n{code};\nEXCEPTION WHEN duplicate_object OR duplicate_table "
            "OR invalid_table_definition THEN NULL;\nEND $aeropt$"
        )
    return statement


def build() -> str:
    parts = [
        "-- new_project.sql — paste into a NEW Supabase project's SQL editor and Run.\n"
        "-- Generated by deploy/new_project_sql.py from db/migrations/. Safe to run again\n"
        "-- if a run stopped halfway. Creates the agent's `public` tables; Django creates\n"
        "-- its own `django` schema with manage.py migrate.\n",
    ]
    sources = [(BASE.name, BASE.read_text())] + [
        (p.name, p.read_text())
        for p in sorted(MIGRATIONS.glob("0[0-9][0-9]_*.sql"))
        if p.name != BASE.name and p.name not in SKIP
    ]
    for name, sql in sources:
        statements = [s for s in split_statements(sql) if not retired(s)]
        body = ";\n\n".join(rerunnable(s) for s in statements)
        parts.append(f"\n-- ===== {name} =====\n{body};\n")
    return "\n".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dump", type=Path, help="schema dump to refresh 000_public_base.sql from")
    args = ap.parse_args()
    if args.dump:
        BASE.write_text(extract_public(args.dump.read_text()))
    OUT.write_text(build())
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
