"""Draft JEE Advanced teaching notes for one chapter, for a human to review.

    .venv/bin/python -m local_ingest.advanced_notes.generate "Rotational Dynamics" --subject Physics

The corpus teaches Advanced chapters from NCERT-level theory (about 1,100 characters a
section). What Advanced adds is what the official papers actually ask: results beyond
NCERT, the recurring problem patterns, and the traps. This asks a model to write that from
the chapter's own official questions plus its theory text, and saves it as a DRAFT.

Drafts are never loaded into the index. A reference note is cited to students as
"Aeropt reference notes" (see local_ingest/reference_notes.py), so an unreviewed error
would be repeated with a citation. Review a draft, correct it against a source, then move
the approved text into reference_notes.py.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from openai import OpenAI

import config
from retrieval import store
from utils.llm import complete_text

DRAFTS = Path(__file__).resolve().parent / "drafts"

_PROMPT = """You are writing study notes for a JEE Advanced aspirant on the chapter "{chapter}" ({subject}).

You are given (1) the chapter's theory text from NCERT / H.C. Verma and (2) official JEE Advanced
questions from this chapter with their official answers. Write notes that cover what Advanced
asks BEYOND NCERT.

Sections, in this order, as markdown:
## Results you must know beyond NCERT
Formulas and facts the questions below rely on that the theory text does not state. Every
formula in LaTeX ($...$). If a result is not in the theory text or the questions, write
"[verify]" after it.
## Recurring problem patterns
4 to 6 patterns. For each: how to recognise it, the method in numbered steps, and the ids of the
questions below that use it (in backticks).
## Common traps
Mistakes the questions are built to catch (sign conventions, missing cases, unit slips).
## Quick self-check
3 short questions with one-line answers, derived only from the material.

Rules: use only the material below and standard, well-established {subject}; do not invent
numbers; do not cite years or papers except the question ids given; plain sentences, no em dashes.

THEORY:
{theory}

OFFICIAL QUESTIONS:
{questions}
"""


def _clip(text: str, n: int) -> str:
    text = re.sub(r"\s+", " ", text or "").strip()
    return text if len(text) <= n else text[:n] + "..."


def build_prompt(chapter: str, subject: str, theory_rows, question_rows) -> str:
    theory = "\n\n".join(f"- ({r['source_book']}) {_clip(r['core_text'], 1400)}" for r in theory_rows)
    questions = "\n\n".join(
        f"[{r['content_id']}] {_clip(r['core_text'], 600)}\n   official answer: {_clip(str(r['answer']), 80)}"
        for r in question_rows
    )
    return _PROMPT.format(chapter=chapter, subject=subject, theory=theory, questions=questions)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("chapter")
    ap.add_argument("--subject", required=True, choices=["Physics", "Chemistry", "Mathematics"])
    ap.add_argument("--questions", type=int, default=14)
    ap.add_argument("--theory", type=int, default=8)
    args = ap.parse_args()

    theory = store.query(
        """select source_book, core_text from public.content
           where subject = %s and chapter = %s and content_type = 'Theory'
           order by length(core_text) desc limit %s""",
        (args.subject, args.chapter, args.theory),
    )
    questions = store.query(
        f"""select c.content_id, c.core_text, c.structured->>'answer' as answer from public.content c
            where c.subject = %s and c.chapter = %s and c.content_type = 'PYQ' and c.target_exam = 'Jee Advanced'
              and {store.FIGURE_READY_SQL}
            order by c.content_id limit %s""",
        (args.subject, args.chapter, args.questions),
    )
    if not theory or not questions:
        raise SystemExit(f"Nothing to work from for {args.subject} / {args.chapter}: "
                         f"{len(theory)} theory rows, {len(questions)} questions.")

    client = OpenAI(api_key=config.LLM_API_KEY, base_url=config.LLM_BASE_URL)
    text, model = complete_text(
        client=client, model=config.LEARNING_AGENT_MODEL,
        messages=[{"role": "user", "content": build_prompt(args.chapter, args.subject, theory, questions)}],
        fallback_models=config.LEARNING_AGENT_FALLBACK_MODELS, min_chars=800, temperature=0.2, max_tokens=3500,
    )

    DRAFTS.mkdir(parents=True, exist_ok=True)
    path = DRAFTS / (re.sub(r"[^a-z0-9]+", "_", args.chapter.lower()).strip("_") + ".md")
    path.write_text(
        f"<!-- DRAFT. Not loaded into the index. Generated by {model} from {len(theory)} theory rows and "
        f"{len(questions)} official questions. A reviewer must check every formula before this moves to "
        f"reference_notes.py. -->\n\n# {args.chapter} ({args.subject}): JEE Advanced notes\n\n{text.strip()}\n"
    )
    print(f"wrote {path} ({len(text)} chars, {model})")


if __name__ == "__main__":
    main()
